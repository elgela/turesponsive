<h2 style="color: red;text-align: center;text-decoration: underline;">Consejos</h2>
<h4 style="color: brown;">Principios clave</h4>
<ul>
    <li><h5>Rapidez y Funcionalidad: </h5>Optimiza imágenes y código para que cargue rápido. Usa un diseño que funcione en cualquier dispositivo (responsive).</li>
    <li><h5>Usabilidad (UX): </h5>Crea menús intuitivos, botones grandes y fáciles de tocar en móviles, y un pie de página útil.</li>
    <li><h5>Jerarquía Visual: </h5>Guía la vista del usuario con tamaño, color y espacio para destacar lo más importante.</li>
</ul>
<h4 style="color: brown;">Contenido y estilo</h4>
<ul>
    <li><h5>Tipografía: </h5>Usa fuentes claras (como Open Sans), no más de 2-3 estilos, con tamaño de al menos 12pt. Divide el texto en párrafos cortos y usa viñetas.</li>
    <li><h5>Colores: </h5>Elige colores que apelen a tu audiencia y la psicología del color. Asegúrate de que el color de los CTA contraste bien con el fondo.</li>
    <li><h5>Imágenes: </h5>Usa imágenes de alta calidad, pero optimizadas para que no ralenticen la carga.</li>
</ul>
<h4 style="color: brown;">Aspectos Técnicos y Avanzados</h4>
<ul>
    <li><h5>Accesibilidad (WCAG): </h5>Diseña para todos, incluyendo personas con daltonismo o discapacidades. Usa etiquetas alt en imágenes y contrastes adecuados.</li>
    <li><h5>IA y Personalización: </h5>Considera usar IA para personalizar la experiencia del usuario, una tendencia fuerte en 2025.</li>
    <li><h5>Llamadas a la Acción (CTA): </h5>Deben ser visibles, específicas ("Regístrate", "Descarga ahora") y guiar al usuario.</li>
</ul>
<h4 style="color: brown;">Mejores Prácticas Adicionales</h4>
<ul>
    <li><h5>Consistencia: </h5>Mantén un diseño, colores y tipografía uniformes en todo el sitio.</li>
    <li><h5>Pruebas: </h5>Prueba tu diseño con usuarios reales para obtener retroalimentación y mejorar.</li>
</ul>

