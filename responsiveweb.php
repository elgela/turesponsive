    <div>
        <h2>🕰️ Orígenes y evolución</h2>
    </div>
    <ul>
        <li>2008: El W3C introduce la idea de One Web, una web accesible desde cualquier dispositivo.</li>
        <li>2010: El diseñador Ethan Marcotte acuña el término Responsive Web Design en la revista A List Apart, proponiendo tres pilares:
            <ul>
                <li>Media queries (consultas de estilo según tamaño de pantalla).</li>
                <li>Layouts fluidos basados en porcentajes.</li>
                <li>Imágenes flexibles que se ajustan automáticamente.</li>
            </ul>
        </li>
        <li>2012: Surgen frameworks como Bootstrap, Foundation y Materialize, que facilitan la creación de sitios responsivos sin partir de cero.</li>
        <li>2015 en adelante: Google comienza a favorecer los sitios responsivos en sus resultados de búsqueda, consolidando esta práctica como estándar global.</li>
    </ul>
</div>
